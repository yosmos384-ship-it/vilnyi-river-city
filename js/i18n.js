// Localised replacement for data.js unitLabel(): "Building C3 · Stair 1 · Floor 5 · Apt 12" in the current language.
export function unitLabelL(u) {
  const fl = u.floor === 0 ? t('ul.ground') : `${t('ul.floor')} ${u.floor === TOP_FLOOR ? '10/10D' : u.floor}`;
  return `${t('ul.building')} ${u.building} · ${t('ul.stair')} ${u.stair} · ${fl} · ${t('ul.apt')} ${u.apNo}`;
}

// data.js payment plans → translated label/description (all 8 languages live under terms.plan.<id>.*)
export function planText(p, field = 'label') {
  const k = `terms.plan.${p.id}.${field}`; const s = t(k);
  return s === k ? pick(p[field]) : s;
}
