// t('unit.floor', {n: 5}) — falls back to English, then to the key itself.
export function t(key, vars) {
  let s = I18N[lang]?.[key] ?? COMMON[key] ?? I18N.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

// Pick a {he,en,ru,…} object from data.js in the current language (English fallback).
export function pick(obj) { return obj ? (obj[lang] ?? obj.en ?? '') : ''; }

// Current-language number formatting for plain counts (prices always use data.js money()).
export function num(n) { try { return Number(n).toLocaleString(lang === 'he' ? 'he-IL' : lang); } catch (e) { return String(n); } }

const listeners = new Set();
export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function setLang(l) {
  if (!LANG_CODES.includes(l)) l = DEFAULT_LANG;
  lang = l; dir = langInfo(l).dir;
  const html = document.documentElement;
  html.lang = l; html.dir = dir;
  try { localStorage.setItem('vrc.lang', l); } catch (e) { /* storage blocked */ }
  applyDom(document);
  listeners.forEach(fn => { try { fn(l); } catch (e) { console.error(e); } });
}

// Fill [data-i18n] (textContent), [data-i18n-attr="attr:key;attr2:key2"].
export function applyDom(root) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach(el => {
    el.dataset.i18nAttr.split(';').forEach(pair => { const [a, k] = pair.split(':'); if (a && k) el.setAttribute(a.trim(), t(k.trim())); });
  });
  if (root === document) {
    document.title = t('meta.title');
    document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.desc'));
  }
}

export function initialLang() {
  let l = null;
  try { l = new URLSearchParams(location.search).get('lang'); } catch (e) { /* ignore */ }
  if (!LANG_CODES.includes(l)) { try { l = localStorage.getItem('vrc.lang'); } catch (e) { l = null; } }
  return LANG_CODES.includes(l) ? l : DEFAULT_LANG;
}

