// CRM strings in the 8 site languages. tc(key, vars) = current UI language; tcL(lang, key, vars) = a given language
// (documents and emails use the CLIENT's language, not the operator's). Fallback: language → site i18n alias → English.
import { lang, I18N, LANGS } from '../i18n.js';

export const CRM = {};

function alias(l, key) {
  if (key.startsWith('face.')) return I18N[l]?.[key];
  if (key.startsWith('u.')) return I18N[l]?.['ul.' + key.slice(2)];
  if (key.startsWith('langName.')) return LANGS.find(x => x.code === key.slice(9))?.name;
  return undefined;
}
export function tcL(l, key, vars) {
  let s = CRM[l]?.[key] ?? alias(l, key) ?? CRM.en[key] ?? alias('en', key) ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}
